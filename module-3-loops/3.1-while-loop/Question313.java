import java.util.Scanner;

public class Question313 {
    public static void main(String[] args) {

        int sum = 0, i = 1;
        while (i <= 5) {
            sum += i;
            i++;
        }
        System.out.println(sum); // Output: 1 + 2 + 3 + 4 + 5 => 15
    }
}
