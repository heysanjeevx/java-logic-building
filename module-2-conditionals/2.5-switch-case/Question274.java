public class Question274 {
    public static void main(String[] args) {
        int n = 2;

        switch (n) {
            case 1:
                System.out.println("One");
            case 2:
                System.out.println("Two");
            case 3:
                System.out.println("Three");
            default:
                System.out.println("Default");

            // Output:
                // Two
                // Three
                // Default
        }
    }
}
