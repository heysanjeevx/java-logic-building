public class Question282 {
    public static void main(String[] args) {
        int n = 0;
        switch (n) {
            case 0:
                System.out.println("Zero");
            case 1:
                System.out.println("One");
            case 2:
                System.out.println("Two");
                break;
            default:
                System.out.println("Other");

            // Output:
                // Zero
                // One
                // Two
        }
    }
}
